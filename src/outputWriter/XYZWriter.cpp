#include "outputWriter/XYZWriter.h"

#include <spdlog/spdlog.h>

#include <iomanip>
#include <sstream>

#include "ParticleContainer.h"

namespace output_writer {

void XYZWriter::Write(const ParticleContainer &particles, int iteration) {
    std::ofstream file;
    std::stringstream name;
    name << prefix_ << "_" << std::setfill('0') << std::setw(4) << iteration << ".xyz";
    auto path = dir_ / name.str();
    file.open(path);
    if (!file) {
        SPDLOG_ERROR("Could not open {}", path.string());
        return;
    }
    file << particles.size() << std::endl;
    file << "Generated by MolSim. See http://openbabel.org/wiki/XYZ_(format) for "
            "file format doku."
         << std::endl;

    for (auto p : particles) {
        Vec3 x = p.x();
        file << "Ar ";
        file.setf(std::ios_base::showpoint);

        for (auto &xi : x) {
            file << xi << " ";
        }

        file << std::endl;
    }

    SPDLOG_DEBUG("Wrote {}", path.string());
    file.close();
}

}  // namespace output_writer
